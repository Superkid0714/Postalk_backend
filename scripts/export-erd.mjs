// Export the checked-in schema in an isolated, in-memory PostgreSQL instance.
// No .env loading, network connection, or production database access.
import { PGlite } from "@electric-sql/pglite";
import { mkdir, readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const db = await PGlite.create();
const quote = (value) => `'${String(value).replaceAll("\\", "\\\\").replaceAll("'", "\\'").replaceAll("\n", " ")}'`;
try {
  await db.exec("create role anon; create role authenticated; create role service_role;");
  await db.exec((await readFile(new URL("supabase/schema.sql", root), "utf8")).replace("create extension if not exists pgcrypto;", ""));
  const tables = (await db.query("select tablename from pg_tables where schemaname='public' order by tablename")).rows;
  const header = (name, note) => ["// Generated by: node scripts/export-erd.mjs", "// Source: supabase/schema.sql; implemented repository model, NOT a live database inspection.", "// Functions, triggers, RLS policies, compatibility views and grants remain authoritative in SQL.", `Project ${name} {`, "  database_type: 'PostgreSQL'", `  Note: ${quote(note)}`, "}", ""];
  const blocks = new Map();
  const refs = [];
  for (const { tablename: table } of tables) {
    const lines = [];
    const columns = (await db.query(`select a.attname as name, format_type(a.atttypid,a.atttypmod) as type, a.attnotnull as required,
      pg_get_expr(d.adbin,d.adrelid) as default_value from pg_attribute a
      left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum
      where a.attrelid=$1::regclass and a.attnum>0 and not a.attisdropped order by a.attnum`, [table])).rows;
    const constraints = (await db.query(`select contype, pg_get_constraintdef(oid) as definition from pg_constraint where conrelid=$1::regclass order by conname`, [table])).rows;
    const indexes = (await db.query("select indexdef from pg_indexes where schemaname='public' and tablename=$1 order by indexname", [table])).rows;
    const pk = constraints.find(c => c.contype === 'p')?.definition.match(/\(([^)]+)\)/)?.[1].split(',').map(s => s.trim()) ?? [];
    const uniqueIndexes = (await db.query(`select (select json_agg(a.attname order by k.ordinality)
      from unnest(i.indkey) with ordinality as k(attnum, ordinality)
      join pg_attribute a on a.attrelid=i.indrelid and a.attnum=k.attnum) as columns
      from pg_index i where i.indrelid=$1::regclass and i.indisunique and not i.indisprimary
      and i.indpred is null and i.indexprs is null`, [table])).rows;
    const unique = uniqueIndexes.map(i => i.columns);
    lines.push(`Table ${table} {`);
    for (const column of columns) {
      const settings = [];
      if (pk.length === 1 && pk[0] === column.name) settings.push('pk');
      if (column.required) settings.push('not null');
      if (unique.some(cols => cols.length === 1 && cols[0] === column.name)) settings.push('unique');
      if (column.default_value !== null) settings.push(`default: \`${column.default_value}\``);
      lines.push(`  ${column.name} ${/\s/.test(column.type) ? `"${column.type}"` : column.type}${settings.length ? ` [${settings.join(', ')}]` : ''}`);
    }
    const composite = [...(pk.length > 1 ? [{ cols: pk, kind: 'pk' }] : []), ...unique.filter(c => c.length > 1).map(cols => ({ cols, kind: 'unique' }))];
    if (composite.length) lines.push('  indexes {', ...composite.map(c => `    (${c.cols.join(', ')}) [${c.kind}]`), '  }');
    const notes = [...constraints.filter(c => c.contype === 'c').map(c => c.definition), ...indexes.map(i => i.indexdef)];
    if (table === 'users') notes.unshift('Currently no FK to stores. Exhibition integer user_id does NOT reference this UUID primary key.');
    if (table.startsWith('exhibition_')) notes.unshift('Opt-in shared exhibition namespace. user_id=1 is not an authenticated account FK.');
    if (['contents', 'input_templates', 'script_jobs'].includes(table)) notes.unshift('Implemented canonical table. Original exhibition_* name is an updatable security-invoker compatibility view, not another table. user_id=1 remains a shared demo identity.');
    if (table === 'contents') notes.unshift('Compatibility parent submissions stores caption/Instagram JSON for legacy publishers. Triggers synchronize caption/status and publication history in the same transaction.');
    if (table === 'concept_versions') notes.unshift('Immutable supplied template snapshot. Vendor version plus definition digest distinguishes dynamic scene/menu variants; final designer concepts are not invented here.');
    if (notes.length) lines.push(`  Note: ${quote(notes.join('; '))}`);
    lines.push('}', '');
    blocks.set(table, lines);
    for (const constraint of constraints.filter(c => c.contype === 'f')) {
      const match = constraint.definition.match(/^FOREIGN KEY \(([^)]+)\) REFERENCES (?:public\.)?(\w+)\(([^)]+)\)(.*)$/);
      if (!match) throw new Error(`Unsupported FK: ${constraint.definition}`);
      const [, source, target, dest, suffix] = match;
      const sourceColumns = source.split(',').map(s => s.trim());
      const destColumns = dest.split(',').map(s => s.trim());
      const one = [pk, ...unique].some(key => JSON.stringify(key) === JSON.stringify(sourceColumns));
      const field = cols => cols.length === 1 ? cols[0] : `(${cols.join(', ')})`;
      const action = suffix.match(/ON DELETE (CASCADE|SET NULL|RESTRICT|NO ACTION)/)?.[1].toLowerCase();
      const nullable = sourceColumns.some(name => !columns.find(c => c.name === name)?.required);
      // DBML short-form one-to-one refs put the FK on the RIGHT.
      const relationship = one
        ? `${target}.${field(destColumns)} ${nullable ? '?-' : '-'} ${table}.${field(sourceColumns)}`
        : `${table}.${field(sourceColumns)} ${nullable ? '>?' : '>'} ${target}.${field(destColumns)}`;
      refs.push({ source: table, target, text: `Ref: ${relationship}${action ? ` [delete: ${action}]` : ''}` });
    }
  }
  await mkdir(new URL('docs/erd/', root), { recursive: true });
  const lines = [...header('postalk_current', 'Implemented repository schema, not confirmation of deployment. Supabase is the DB and file storage. No automatic file deletion. exhibition_templates/exhibition_script_jobs/exhibition_ads are compatibility views. user_id=1 is not users.id.'), ...[...blocks.values()].flat(), ...refs.map(ref => ref.text), ''];
  await writeFile(new URL('docs/erd/current.dbml', root), lines.join('\n'));
  const workflow = new Set(['stores','input_templates','concept_versions','creation_sessions','creation_scenes','media_assets','scene_media','script_jobs','contents','generation_jobs','content_outputs','publication_attempts']);
  const subset = [...header('postalk_workflow', 'Implemented workflow subset of current.dbml. Legacy QR/session tables, submission compatibility parents, leases and references to omitted tables are hidden for readability. These functions and triggers are implemented, but deploying SQL and external AI integrations are separate steps.'), ...[...blocks].filter(([name]) => workflow.has(name)).flatMap(([, block]) => block), ...refs.filter(ref => workflow.has(ref.source) && workflow.has(ref.target)).map(ref => ref.text), ''];
  await writeFile(new URL('docs/erd/workflow.dbml', root), subset.join('\n'));
  console.log(`Exported ${tables.length} tables and ${refs.length} foreign keys to docs/erd/current.dbml`);
} finally { await db.close(); }
